depths = {'Creek': 1.2, 'River': 3.5, 'Pond': 0.8, 'Lake': 2.6}

site_name = input('Please enter a site name: ').capitalize() #It capitalizes the first letter and makes the rest lowercase, so it can be found regardless of how it is written.

if site_name in depths:
  print('The water depth at', site_name, 'is', depths[site_name], 'meters.')
else:
  print('The site was not found.')